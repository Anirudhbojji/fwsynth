"""Deterministic rendering of a verified ruleset to nftables.

Rendering is pure templating from the verified IR — the LLM never touches
this stage, so output correctness reduces to IR correctness (which the
verifier just proved).
"""

from .model import Rule, Ruleset


def _match_expr(rule: Rule) -> str:
    parts = []
    if rule.src != "0.0.0.0/0":
        parts.append(f"ip saddr {rule.src}")
    if rule.dst != "0.0.0.0/0":
        parts.append(f"ip daddr {rule.dst}")
    if rule.proto == "icmp":
        parts.append("ip protocol icmp")
    elif rule.proto in ("tcp", "udp"):
        if rule.dport_lo == 0 and rule.dport_hi == 65535:
            parts.append(f"ip protocol {rule.proto}")
        elif rule.dport_lo == rule.dport_hi:
            parts.append(f"{rule.proto} dport {rule.dport_lo}")
        else:
            parts.append(f"{rule.proto} dport {rule.dport_lo}-{rule.dport_hi}")
    elif rule.proto == "any" and not (rule.dport_lo == 0 and rule.dport_hi == 65535):
        # port range without a protocol applies to both tcp and udp
        parts.append(f"meta l4proto {{ tcp, udp }} th dport {rule.dport_lo}-{rule.dport_hi}")
    return " ".join(parts)


def render_nftables(ruleset: Ruleset, chain: str = "forward") -> str:
    policy = "accept" if ruleset.default == "allow" else "drop"
    lines = [
        "#!/usr/sbin/nft -f",
        "# generated by fwsynth — ruleset verified against intent spec before render",
        "",
        "table inet fwsynth {",
        f"  chain {chain} {{",
        f"    type filter hook {chain} priority 0; policy {policy};",
    ]
    for rule in ruleset.rules:
        action = "accept" if rule.action == "allow" else "drop"
        match = _match_expr(rule)
        comment = f' comment "{rule.comment}"' if rule.comment else ""
        line = f"    {match} {action}{comment}" if match else f"    {action}{comment}"
        lines.append(line)
    lines += ["  }", "}", ""]
    return "\n".join(lines)
